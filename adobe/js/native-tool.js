(function (root) {
  "use strict";
  // This function is serialized into a standalone ES3-compatible .jsx file.
  function panelRuntime(thisObj, definition, execute) {
    var docked = typeof Panel !== "undefined" && thisObj instanceof Panel;
    var ui = docked ? thisObj : new Window("palette", definition.name, undefined, { resizeable: true });
    ui.orientation = "column";
    ui.alignChildren = ["fill", "top"];
    ui.spacing = 10;
    ui.margins = 16;
    var description = ui.add("statictext", undefined, definition.description, { multiline: true });
    description.preferredSize.width = 320;
    var controls = {};
    var groups = {};
    var i;
    for (i = 0; i < definition.options.length; i += 1) {
      var field = definition.options[i];
      var section = field.group || "Options";
      if (!groups[section]) {
        groups[section] = ui.add("panel", undefined, section);
        groups[section].orientation = "column";
        groups[section].alignChildren = ["fill", "top"];
        groups[section].margins = 12;
      }
      var row = groups[section].add("group");
      row.orientation = "row"; row.alignChildren = ["left", "center"];
      var control;
      if (field.type === "boolean") {
        control = row.add("checkbox", undefined, field.label);
        control.value = field.defaultValue;
      } else {
        row.add("statictext", undefined, field.label);
        if (field.type === "select") {
          control = row.add("dropdownlist", undefined, field.choices);
          for (var j = 0; j < field.choices.length; j += 1) { if (field.choices[j] === field.defaultValue) { control.selection = j; } }
        } else {
          control = row.add("edittext", undefined, String(field.defaultValue));
          control.characters = 20;
        }
        control.alignment = ["fill", "center"];
      }
      control.helpTip = field.help || field.label;
      controls[field.key] = control;
    }
    var status = ui.add("statictext", undefined, "Ready", { multiline: true });
    status.preferredSize.width = 320;
    var run = ui.add("button", undefined, definition.actionLabel || "Run tool");
    run.helpTip = "Apply this tool to the current After Effects project.";
    run.onClick = function () {
      var options = {};
      try {
        for (var k = 0; k < definition.options.length; k += 1) {
          var f = definition.options[k]; var c = controls[f.key]; var value;
          if (f.type === "boolean") { value = c.value; }
          else if (f.type === "select") { if (!c.selection) { throw new Error("Choose " + f.label); } value = c.selection.text; }
          else { value = c.text; }
          if (f.type === "number") {
            if (!String(value).replace(/\s/g, "")) { throw new Error(f.label + " needs a number."); }
            value = Number(value);
            if (!isFinite(value) || (f.min !== undefined && value < f.min) || (f.max !== undefined && value > f.max)) { throw new Error(f.label + " is outside its allowed range."); }
          }
          if (f.type === "color" && !/^#[0-9a-f]{6}$/i.test(value)) { throw new Error(f.label + " needs a six-digit hex color."); }
          options[f.key] = value;
        }
      } catch (error) { status.text = String(error); return; }
      run.enabled = false;
      var opened = false;
      try {
        app.beginUndoGroup(definition.name); opened = true;
        execute(options);
        status.text = "Completed. Use After Effects Undo to revert.";
      } catch (error2) {
        status.text = "Stopped: " + String(error2) + " Partial changes may remain; use After Effects Undo if needed.";
      } finally {
        if (opened) { app.endUndoGroup(); }
        run.enabled = true;
      }
      ui.layout.layout(true);
    };
    ui.onResizing = ui.onResize = function () { this.layout.resize(); };
    ui.layout.layout(true);
    if (!docked) {
      $.global.AEAgentToolWindows = $.global.AEAgentToolWindows || {};
      var old = $.global.AEAgentToolWindows[definition.id];
      if (old) { try { old.close(); } catch (ignored) {} }
      $.global.AEAgentToolWindows[definition.id] = ui;
      ui.onClose = function () { delete $.global.AEAgentToolWindows[definition.id]; };
      ui.center(); ui.show();
    }
  }
  function generate(tool) {
    var metadata = { id: tool.id, name: tool.name, description: tool.description, options: tool.options, actionLabel: tool.actionLabel || "Run tool" };
    var json = JSON.stringify(metadata).replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");
    return "// Generated by AE Agent. Standalone ScriptUI panel.\n// Dockable when installed in After Effects Scripts/ScriptUI Panels and opened from Window.\n(" + panelRuntime.toString() + ")(this, " + json + ", function(options) {\n" + tool.code + "\n});\n";
  }
  root.AENativeTool = { generate: generate };
  if (typeof module === "object" && module.exports) { module.exports = root.AENativeTool; }
}(typeof window !== "undefined" ? window : this));
